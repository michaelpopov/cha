import Foundation
import WebKit

struct NativeViewState: Equatable {
    var split = false
    var sidebar = true
    var pictures = false
    var toolbar = true
    var chatToolbar = true
    var notesPrompt = true
    var russian = false

    var object: [String: Bool] {
        ["split": split, "sidebar": sidebar, "pictures": pictures, "toolbar": toolbar,
         "chat_toolbar": chatToolbar, "notes_prompt": notesPrompt, "russian": russian]
    }
    static func load(_ url: URL) -> NativeViewState {
        var result = NativeViewState()
        do {
            let data = try Data(contentsOf: url)
            guard let object = try JSONSerialization.jsonObject(with: data) as? [String: Any] else {
                throw NSError(domain: "View preferences must be an object", code: 1)
            }
            var values = result.object
            for (key, value) in object {
                guard values[key] != nil else { NSLog("warning: ignoring unknown View preference %@ in %@", key, url.path); continue }
                guard let number = value as? NSNumber, CFGetTypeID(number) == CFBooleanGetTypeID() else {
                    NSLog("warning: invalid View preference %@ in %@", key, url.path); continue
                }
                values[key] = number.boolValue
            }
            result = NativeViewState(split: values["split"]!, sidebar: values["sidebar"]!, pictures: values["pictures"]!, toolbar: values["toolbar"]!, chatToolbar: values["chat_toolbar"]!, notesPrompt: values["notes_prompt"]!, russian: values["russian"]!)
        } catch {
            let failure = error as NSError
            if failure.domain != NSCocoaErrorDomain || failure.code != CocoaError.fileReadNoSuchFile.rawValue {
                NSLog("warning: cannot read View preferences at %@: %@", url.path, error.localizedDescription)
            }
        }
        return result
    }
    func save(_ url: URL) {
        do {
            var data = try JSONSerialization.data(withJSONObject: object, options: [.sortedKeys])
            data.append(10)
            try data.write(to: url, options: .atomic)
        } catch { NSLog("warning: cannot write View preferences at %@: %@", url.path, error.localizedDescription) }
    }
    var json: String {
        String(data: try! JSONSerialization.data(withJSONObject: object), encoding: .utf8)!
    }
}

private let chaMessageHandlerName = "cha"

func nativeAttemptId(_ value: Any?) -> Int? {
    guard let number = value as? NSNumber,
          CFGetTypeID(number) != CFBooleanGetTypeID() else {
        return nil
    }
    let double = number.doubleValue
    guard double >= 1, double <= 9_007_199_254_740_991,
          let attempt = Int(exactly: double) else {
        return nil
    }
    return attempt
}

func nativeBootstrapJavaScript(connectionId: String, view: NativeViewState = NativeViewState()) -> String {
    // connectionId is generated by native code (view-N), never user content.
    """
    window.__CHA_NATIVE_INITIAL_VIEW_STATE__ = \(view.json);
    window.__CHA_NATIVE_CONNECTION_ID__ = "\(connectionId)";
    window.__CHA_NATIVE_CONTEXT_EPOCH__ = 0;
    window.__CHA_NATIVE_QUEUE__ = window.__CHA_NATIVE_QUEUE__ || [];
    if (typeof window.__CHA_NATIVE_RECEIVE__ !== "function") {
      window.__CHA_NATIVE_RECEIVE__ = function(batch) {
        window.__CHA_NATIVE_QUEUE__.push(batch);
      };
    }
    window.__CHA_NATIVE_POST__ = function(message) {
      if (window.webkit && window.webkit.messageHandlers
          && window.webkit.messageHandlers.cha) {
        window.webkit.messageHandlers.cha.postMessage(message);
      }
    };
    window.__CHA_NATIVE_SAVE_PENDING__ = {};
    window.__CHA_NATIVE_SAVE_SEQ__ = 0;
    window.__CHA_NATIVE_SAVE_SESSION__ = function(suggestedName, forumId, sessionId) {
      return new Promise(function(resolve, reject) {
        var id = String(++window.__CHA_NATIVE_SAVE_SEQ__);
        window.__CHA_NATIVE_SAVE_PENDING__[id] = {resolve: resolve, reject: reject};
        window.__CHA_NATIVE_POST__(JSON.stringify({
          native_action: "save_session",
          id: id,
          connection_id: window.__CHA_NATIVE_CONNECTION_ID__,
          context_epoch: window.__CHA_NATIVE_CONTEXT_EPOCH__,
          suggested_name: suggestedName,
          forum_id: forumId,
          session_id: sessionId
        }));
      });
    };
    window.__CHA_NATIVE_EXPORT_NOTE_FOLDER__ = function(suggestedName, folderId) {
      return new Promise(function(resolve, reject) {
        var id = String(++window.__CHA_NATIVE_SAVE_SEQ__);
        window.__CHA_NATIVE_SAVE_PENDING__[id] = {resolve: resolve, reject: reject};
        window.__CHA_NATIVE_POST__(JSON.stringify({
          native_action: "export_note_folder",
          id: id,
          connection_id: window.__CHA_NATIVE_CONNECTION_ID__,
          context_epoch: window.__CHA_NATIVE_CONTEXT_EPOCH__,
          suggested_name: suggestedName,
          folder_id: folderId
        }));
      });
    };
    window.__CHA_NATIVE_IMPORT_NOTE_FOLDER__ = function(parentId) {
      return new Promise(function(resolve, reject) {
        var id = String(++window.__CHA_NATIVE_SAVE_SEQ__);
        window.__CHA_NATIVE_SAVE_PENDING__[id] = {resolve: resolve, reject: reject};
        window.__CHA_NATIVE_POST__(JSON.stringify({
          native_action: "import_note_folder",
          id: id,
          connection_id: window.__CHA_NATIVE_CONNECTION_ID__,
          context_epoch: window.__CHA_NATIVE_CONTEXT_EPOCH__,
          parent_id: parentId
        }));
      });
    };
    window.__CHA_NATIVE_SAVE_DONE__ = function(id, ok, message) {
      var pending = window.__CHA_NATIVE_SAVE_PENDING__[id];
      if (!pending) return;
      delete window.__CHA_NATIVE_SAVE_PENDING__[id];
      if (ok) pending.resolve();
      else pending.reject(new Error(message || "Save failed"));
    };
    window.__CHA_NATIVE_PREPARE_CLOSE__ = function(attemptId) {
      window.__CHA_NATIVE_POST__(JSON.stringify({
        native_action: "close_reply",
        connection_id: window.__CHA_NATIVE_CONNECTION_ID__,
        attempt_id: attemptId,
        result: "ready"
      }));
    };
    window.__CHA_NATIVE_CLOSE_ABORTED__ = function(attemptId) {};
    """
}

let chaCloseResponseWait: TimeInterval = 15

func makeCloseResponseTimer(handler: @escaping () -> Void) -> Timer {
    let timer = Timer(timeInterval: chaCloseResponseWait, repeats: false) { timer in
        timer.invalidate()
        handler()
    }
    // common includes NSModalPanelRunLoopMode, which is the pending-termination loop.
    RunLoop.main.add(timer, forMode: .common)
    return timer
}

func nativeBootstrapUserScript(connectionId: String, view: NativeViewState = NativeViewState()) -> WKUserScript {
    WKUserScript(
        source: nativeBootstrapJavaScript(connectionId: connectionId, view: view),
        injectionTime: .atDocumentStart,
        forMainFrameOnly: true)
}

func makeNativeWebViewConfiguration(assetRoot: URL) -> (
    WKWebViewConfiguration, ChaAssetSchemeHandler
) {
    let configuration = WKWebViewConfiguration()
    configuration.mediaTypesRequiringUserActionForPlayback = []
    let handler = ChaAssetSchemeHandler(root: assetRoot)
    configuration.setURLSchemeHandler(handler, forURLScheme: chaAssetScheme)
    return (configuration, handler)
}

func isSameDocumentHashChange(from current: URL?, to next: URL?) -> Bool {
    guard let current, let next, current.fragment != next.fragment,
          var from = URLComponents(url: current, resolvingAgainstBaseURL: false),
          var to = URLComponents(url: next, resolvingAgainstBaseURL: false) else { return false }
    from.fragment = nil
    to.fragment = nil
    return from == to
}

final class ChaNativeDeliveryBox: @unchecked Sendable {
    weak var owner: ChaNativeBridgeReceiver?
}

private func chaDeliveryTrampoline(
    _ context: UnsafeMutableRawPointer?,
    _ connection: UnsafePointer<CChar>?,
    _ json: UnsafePointer<CChar>?
) {
    guard let context, let connection, let json else { return }
    let box = Unmanaged<ChaNativeDeliveryBox>.fromOpaque(context).takeUnretainedValue()
    let connectionId = String(cString: connection)
    let payload = String(cString: json)
    DispatchQueue.main.async {
        box.owner?.deliver(connectionId: connectionId, json: payload)
    }
}

final class ChaNativeBridgeReceiver: NSObject, WKScriptMessageHandler {
    private let runtime: OpaquePointer
    private let deliveryBox = ChaNativeDeliveryBox()
    private var retainedDeliveryContext: UnsafeMutableRawPointer?
    private weak var webView: WKWebView?
    private(set) var connectionId: String?
    var isTrustedOrigin: ((WKSecurityOrigin) -> Bool) = { origin in
        isChaAssetOrigin(origin)
    }
    var saveSession: ((String, String, UInt64, String, String, String) -> Void)?
    var exportNoteFolder: ((String, String, UInt64, String, Int64) -> Void)?
    var importNoteFolder: ((String, String, UInt64, Int64) -> Void)?
    var onCloseReply: ((String, Int, String) -> Void)?
    var onPageClose: (() -> Void)?
    var currentView: (() -> NativeViewState)?
    var onLayoutChanged: ((Bool, Bool, Bool, Bool, Bool, Bool, Bool) -> Void)?

    init(runtime: OpaquePointer) {
        self.runtime = runtime
        super.init()
        deliveryBox.owner = self
    }

    deinit {
        if retainedDeliveryContext != nil {
            clearDeliveryCallback()
        }
    }

    func attach(to webView: WKWebView, mediaHandler: ChaAssetSchemeHandler? = nil) {
        self.webView = webView
        webView.configuration.userContentController.add(
            self, name: chaMessageHandlerName)
        if let mediaHandler {
            mediaHandler.readMedia = { [weak self] id in
                self?.readMedia(id)
            }
            mediaHandler.readMediaChunk = { [weak self] id, offset in
                self?.readMediaChunk(id, offset: offset) ?? (404, "text/plain", Data(), false)
            }
        }
        installDeliveryCallback()
        prepareDocumentReplacement()
    }

    private func readMedia(_ resourceId: String) -> (type: String, body: Data)? {
        guard let connectionId else { return nil }
        var mime: UnsafeMutablePointer<CChar>?
        var bytes: UnsafeMutableRawPointer?
        var size: UInt64 = 0
        var error: UnsafeMutablePointer<CChar>?
        let ok = connectionId.withCString { connection in
            resourceId.withCString { resource in
                cha_runtime_read_resource(
                    runtime, connection, resource, &mime, &bytes, &size, &error)
            }
        }
        cha_string_free(error)
        defer {
            cha_string_free(mime)
            cha_bytes_free(bytes)
        }
        guard ok != 0, let bytes else { return nil }
        let type = mime.map { String(cString: $0) } ?? "application/octet-stream"
        let body = Data(bytes: bytes, count: Int(size))
        return (type, body)
    }

    private func readMediaChunk(_ resourceId: String, offset: UInt64) -> (status: Int, type: String, body: Data, complete: Bool) {
        guard let connectionId else { return (404, "text/plain", Data(), false) }
        var mime: UnsafeMutablePointer<CChar>?
        var bytes: UnsafeMutableRawPointer?
        var size: UInt64 = 0
        var complete: Int32 = 0
        let status = connectionId.withCString { connection in
            resourceId.withCString { resource in
                cha_runtime_read_resource_chunk(runtime, connection, resource, offset, &mime, &bytes, &size, &complete)
            }
        }
        defer { cha_string_free(mime); cha_bytes_free(bytes) }
        return (Int(status), mime.map { String(cString: $0) } ?? "application/octet-stream",
                bytes.map { Data(bytes: $0, count: Int(size)) } ?? Data(), complete != 0)
    }

    func detach() {
        if let connectionId {
            cha_runtime_close_connection(runtime, connectionId)
            self.connectionId = nil
        }
        clearDeliveryCallback()
        webView?.configuration.userContentController
            .removeScriptMessageHandler(forName: chaMessageHandlerName)
        webView = nil
    }

    private func installDeliveryCallback() {
        clearDeliveryCallback()
        let context = Unmanaged.passRetained(deliveryBox).toOpaque()
        retainedDeliveryContext = context
        cha_runtime_set_delivery_callback(
            runtime, chaDeliveryTrampoline, context)
    }

    private func clearDeliveryCallback() {
        cha_runtime_set_delivery_callback(runtime, nil, nil)
        if let context = retainedDeliveryContext {
            retainedDeliveryContext = nil
            Unmanaged<ChaNativeDeliveryBox>.fromOpaque(context).release()
        }
    }

    @discardableResult
    func prepareDocumentReplacement() -> String? {
        if let connectionId {
            cha_runtime_close_connection(runtime, connectionId)
            self.connectionId = nil
        }
        var error: UnsafeMutablePointer<CChar>?
        guard let opened = cha_runtime_open_connection(runtime, &error) else {
            cha_string_free(error)
            return nil
        }
        let id = String(cString: opened)
        cha_string_free(opened)
        connectionId = id
        guard let controller = webView?.configuration.userContentController else {
            return id
        }
        controller.removeAllUserScripts()
        controller.addUserScript(nativeBootstrapUserScript(connectionId: id, view: currentView?() ?? NativeViewState()))
        return id
    }

    func willNavigate(_ navigation: WKNavigationAction, in view: WKWebView) {
        if navigation.targetFrame?.isMainFrame == true
            && !isSameDocumentHashChange(from: view.url, to: navigation.request.url) {
            prepareDocumentReplacement()
        }
    }

    func userContentController(
        _ userContentController: WKUserContentController,
        didReceive message: WKScriptMessage
    ) {
        guard message.name == chaMessageHandlerName,
              message.frameInfo.isMainFrame,
              isTrustedOrigin(message.frameInfo.securityOrigin),
              let connectionId,
              let body = message.body as? String else {
            return
        }
        if let data = body.data(using: .utf8),
           let object = try? JSONSerialization.jsonObject(with: data) as? [String: Any],
           let action = object["native_action"] as? String {
            if action == "view_state" {
                guard object["connection_id"] as? String == connectionId,
                      let split = object["split"] as? NSNumber,
                      CFGetTypeID(split) == CFBooleanGetTypeID(),
                      let sidebar = object["sidebar"] as? NSNumber,
                      CFGetTypeID(sidebar) == CFBooleanGetTypeID(),
                      let pictures = object["pictures"] as? NSNumber,
                      CFGetTypeID(pictures) == CFBooleanGetTypeID(),
                      let chatToolbar = object["chat_toolbar"] as? NSNumber,
                      CFGetTypeID(chatToolbar) == CFBooleanGetTypeID(),
                      let toolbar = object["toolbar"] as? NSNumber,
                      CFGetTypeID(toolbar) == CFBooleanGetTypeID(),
                      let notesPrompt = object["notes_prompt"] as? NSNumber,
                      CFGetTypeID(notesPrompt) == CFBooleanGetTypeID(),
                      let russian = object["russian"] as? NSNumber,
                      CFGetTypeID(russian) == CFBooleanGetTypeID() else { return }
                onLayoutChanged?(split.boolValue, sidebar.boolValue, pictures.boolValue, toolbar.boolValue, notesPrompt.boolValue, chatToolbar.boolValue, russian.boolValue)
                return
            }
            if action == "close_reply" {
                guard let attempt = nativeAttemptId(object["attempt_id"]),
                      let result = object["result"] as? String,
                      result == "ready" || result == "cancelled",
                      let originatingConnection = object["connection_id"] as? String,
                      originatingConnection == connectionId else {
                    return
                }
                onCloseReply?(originatingConnection, attempt, result)
                return
            }
            if action == "close" {
                guard let originatingConnection = object["connection_id"] as? String,
                      originatingConnection == connectionId else {
                    return
                }
                onPageClose?()
                return
            }
            guard action == "save_session" || action == "export_note_folder"
                    || action == "import_note_folder",
                  let id = object["id"] as? String,
                  let originatingConnection = object["connection_id"] as? String,
                  originatingConnection == connectionId,
                  let epochNumber = object["context_epoch"] as? NSNumber,
                  CFGetTypeID(epochNumber) != CFBooleanGetTypeID(),
                  epochNumber.doubleValue >= 1,
                  epochNumber.doubleValue <= 9_007_199_254_740_991,
                  let contextEpoch = UInt64(exactly: epochNumber.doubleValue) else {
                return
            }
            if action == "export_note_folder" {
                guard let folderId = nativeAttemptId(object["folder_id"]) else { return }
                exportNoteFolder?(
                    originatingConnection,
                    id,
                    contextEpoch,
                    object["suggested_name"] as? String ?? "folder.sqlite",
                    Int64(folderId))
                return
            }
            if action == "import_note_folder" {
                // A null parent is the vault root.
                var parentId = 0
                if !(object["parent_id"] is NSNull) {
                    guard let parent = nativeAttemptId(object["parent_id"]) else { return }
                    parentId = parent
                }
                importNoteFolder?(originatingConnection, id, contextEpoch, Int64(parentId))
                return
            }
            guard let forumId = object["forum_id"] as? String,
                  let sessionId = object["session_id"] as? String else {
                return
            }
            saveSession?(
                originatingConnection,
                id,
                contextEpoch,
                object["suggested_name"] as? String ?? "session.md",
                forumId,
                sessionId)
            return
        }
        connectionId.withCString { connection in
            body.withCString { json in
                cha_runtime_handle_message(runtime, connection, json)
            }
        }
    }

    func completeSave(
        connectionId: String,
        id: String,
        ok: Bool,
        message: String
    ) {
        guard connectionId == self.connectionId, let webView else { return }
        webView.callAsyncJavaScript(
            """
            if (typeof window.__CHA_NATIVE_SAVE_DONE__ === "function") {
              window.__CHA_NATIVE_SAVE_DONE__(id, ok, message);
            }
            """,
            arguments: ["id": id, "ok": ok, "message": message],
            in: nil,
            in: .page,
            completionHandler: { _ in })
    }

    func setLayout(_ mode: String) {
        guard let connectionId, let webView else { return }
        webView.callAsyncJavaScript(
            """
            if (window.__CHA_NATIVE_CONNECTION_ID__ === connectionId
                && typeof window.__CHA_NATIVE_SET_LAYOUT__ === "function") {
              window.__CHA_NATIVE_SET_LAYOUT__(mode);
            }
            """,
            arguments: ["connectionId": connectionId, "mode": mode],
            in: nil,
            in: .page,
            completionHandler: { _ in })
    }

    func deliver(connectionId: String, json: String) {
        guard connectionId == self.connectionId, let webView else { return }
        guard let data = json.data(using: .utf8),
              let batch = try? JSONSerialization.jsonObject(with: data) else {
            return
        }
        webView.callAsyncJavaScript(
            """
            if (typeof window.__CHA_NATIVE_RECEIVE__ === "function") {
              window.__CHA_NATIVE_RECEIVE__(batch);
            } else {
              (window.__CHA_NATIVE_QUEUE__ = window.__CHA_NATIVE_QUEUE__ || []).push(batch);
            }
            """,
            arguments: ["batch": batch],
            in: nil,
            in: .page,
            completionHandler: { _ in })
    }
}
